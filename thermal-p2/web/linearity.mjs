import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createEvaluator, decodeFieldBasis } from './evaluator.ts';
import { auditLinearity } from './linearity-check.ts';
const root=new URL('../',import.meta.url);
const readJSON=async path=>JSON.parse(await readFile(new URL(path,root),'utf8'));
const model=await readJSON('models/scalar-model.json');
const field=await readJSON('models/field-model.json');
const bytes=await readFile(new URL('models/field-basis.f16',root));
const basis=decodeFieldBasis(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength));
const evaluate=createEvaluator(model,field,basis);
const metrics=auditLinearity(evaluate,(await readJSON('web/holdout-fixtures.json')).rows);
assert.equal(metrics.maxResistanceChange,0);
assert.ok(metrics.maxScalarAffineErrorC<1e-10);
assert.ok(metrics.maxLayerAffineErrorC<1e-10);
assert.ok(metrics.maxFieldRoundingRatio<=1);
assert.equal(metrics.maxZeroPowerErrorC,0);
assert.equal(metrics.coordinateChanges,0);
assert.equal(metrics.maskChanges,0);
const report={...metrics,node:process.version,pass:true,law:'T(P,T_cool)=T_cool+(P/100)*T(100,0)',field_precision:'Float32 output; 4*2^-23*max(1,abs(expected),abs(scaled reference)) tolerance',scope:'Constant conductivity, geometry and h; no temperature-dependent material properties, radiation or nonlinear fluid solve'};
await writeFile(new URL('reports/linearity-v2.json',root),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));