import { createHash } from 'node:crypto';
import { readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(import.meta.dirname, '..');
export const workFontWeights = [400, 500, 600, 700];
export const workFontFamily = 'Noto Sans SC Work Detail';
export const codeLabel = (code) => `U+${code.toString(16).toUpperCase().padStart(4, '0')}`;
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex').match(/.{8}/g);

/** One inventory shared by authoring and ordinary builds, including all menu states. */
export function collectWorkFontInputs(projectRoot = root) {
  const bindings = {};
  const read = (file) => {
    const bytes = readFileSync(path.join(projectRoot, file));
    bindings[file] = digest(bytes);
    return bytes.toString('utf8').replace(/^\uFEFF/, '');
  };
  const contentFiles = (directory) =>
    readdirSync(path.join(projectRoot, directory), { withFileTypes: true })
      .flatMap((entry) => {
        const file = `${directory}/${entry.name}`;
        return entry.isDirectory()
          ? contentFiles(file)
          : /\.(md|mdx)$/.test(entry.name)
            ? [file]
            : [];
      })
      .sort();
  let text = '';
  for (const locale of ['zh', 'en']) {
    const directory = `src/content/work/${locale}`;
    for (const file of contentFiles(directory)) text += read(file);
    const home = JSON.parse(read(`src/content/home/${locale}.json`));
    text += home.name + home.navWork + home.navLab + JSON.stringify(home.footer);
  }
  for (const name of ['WorkDetail', 'MetricRow', 'Header', 'Footer'])
    text += read(`src/components/${name}.astro`);
  text += read('src/scripts/navigation.ts');
  const dictionary = read('src/i18n/dictionaries.ts');
  for (const section of ['nav', 'common', 'work']) {
    const matches = [...dictionary.matchAll(new RegExp(`^  ${section}: \\{(.*?)^  \\},`, 'gms'))];
    if (matches.length !== 2) throw Error(`Review both work dictionary locales: ${section}`);
    text += matches.map((match) => match[1]).join('');
  }
  for (const file of [
    'src/layouts/BaseLayout.astro',
    'src/styles/global.css',
    'src/styles/navigation.css',
    'src/styles/thermal-tokens.css',
    'src/styles/tokens.css',
    'src/styles/work.css',
    'scripts/work-font-inputs.mjs',
    'scripts/subset-work-fonts.py',
  ])
    read(file);
  const requestedCodepoints = [
    ...new Set(Array.from(text, (character) => character.codePointAt(0))),
  ]
    .filter((code) => code > 127)
    .sort((a, b) => a - b)
    .map(codeLabel);
  return { requestedCodepoints, sourceInputsSha256: bindings };
}

export function workFontCss(faces) {
  const blocks = ['/* Generated by scripts/subset-work-fonts.py; WorkDetail pages only. */'];
  for (const face of faces)
    blocks.push(`@font-face {
  font-family: '${workFontFamily}';
  font-style: normal;
  font-display: swap;
  font-weight: ${face.weight};
  src: url('/fonts/work-detail/${face.file}') format('woff2');
  unicode-range: ${face.codepoints.join(', ')};
}`);
  blocks.push(`body.work-detail-page {
  --thermal-font:
    'Geist Variable', '${workFontFamily}', -apple-system, BlinkMacSystemFont, sans-serif;
  font-family: var(--thermal-font);
}`);
  return blocks.join('\n') + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv[2] === '--css')
    process.stdout.write(workFontCss(JSON.parse(readFileSync(process.argv[3], 'utf8')).faces));
  else process.stdout.write(JSON.stringify(collectWorkFontInputs()));
}
