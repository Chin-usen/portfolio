"""Generate two real-weight, route-specific index and generic lab subsets.

Ordinary builds use checked-in WOFF2 files and check-lab-fonts.mjs. This optional
pinned Python authoring tool retains source outlines, metrics and OFL metadata.
"""
from __future__ import annotations
import argparse
import importlib.util
import json
import textwrap
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.unicodedata import mirrored

ROOT = Path(__file__).resolve().parents[1]


def load(name, relative):
    spec = importlib.util.spec_from_file_location(name, ROOT / relative)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


base = load('lab_base', 'scripts/subset-noto-fonts.py')
inputs = load('lab_inputs', 'scripts/lab-font-inputs.py')
OUTPUT = ROOT / 'public/fonts'


def requested(scope):
    bindings = {}
    texts = getattr(inputs, scope + '_text')(bindings)
    codes = {}
    for weight, text in texts.items():
        values = {ord(char) for char in text if ord(char) > 127}
        values |= {mirror for code in tuple(values) if (mirror := mirrored(code)) is not None}
        codes[weight] = values
    return codes, bindings


def css_for(scope, faces):
    family = 'Noto Sans SC Lab ' + scope.title()
    blocks = ['/* Generated by scripts/subset-lab-fonts.py; route-selected in BaseLayout. */']
    for face in faces:
        ranges = textwrap.fill(', '.join(face['codepoints']) + ';', width=100, initial_indent='    ', subsequent_indent='    ', break_long_words=False, break_on_hyphens=False)
        blocks.append("@font-face {\n  font-family: '" + family + "';\n  font-style: normal;\n  font-display: optional;\n  font-weight: " + str(face['weight']) + ";\n  src: url('/fonts/" + face['file'] + "') format('woff2');\n  unicode-range:\n" + ranges + '\n}')
    blocks.append('body.lab-' + scope + "-page {\n  --thermal-font:\n    'Geist Variable', '" + family + "', -apple-system, BlinkMacSystemFont, sans-serif;\n  font-family: var(--thermal-font);\n}")
    return '\n'.join(blocks) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    assert base.fontTools.__version__ == base.FONTTOOLS_VERSION
    assert base.brotli.__version__ == base.BROTLI_VERSION
    package = json.loads((base.PACKAGE / 'package.json').read_text(encoding='utf-8'))
    assert package['version'] == '5.3.1'
    for scope in ('index', 'fallback'):
        codes, bindings = requested(scope)
        manifest_path = OUTPUT / f'noto-sans-sc-lab-{scope}-manifest.json'
        css_path = ROOT / f'src/styles/lab-{scope}-fonts.css'
        if not args.check:
            faces = []
            for weight, values in codes.items():
                source_relative = f'files/noto-sans-sc-chinese-simplified-{weight}-normal.woff2'
                source = base.PACKAGE / source_relative
                with TTFont(source, recalcTimestamp=False) as font:
                    coverage = values & set(font.getBestCmap())
                    assert not {code for code in values - coverage if 0x3400 <= code <= 0x9FFF}, 'Chinese glyph outside source master'
                    options = subset.Options()
                    options.flavor = 'woff2'
                    options.recalc_timestamp = False
                    options.layout_features = ['*']
                    options.name_IDs = ['*']
                    options.name_languages = ['*']
                    options.name_legacy = True
                    options.glyph_names = True
                    options.hinting = True
                    subsetter = subset.Subsetter(options=options)
                    subsetter.populate(unicodes=coverage)
                    subsetter.subset(font)
                    font.flavor = 'woff2'
                    output = OUTPUT / f'noto-sans-sc-lab-{scope}-{weight}-normal.woff2'
                    font.save(output, reorderTables=True)
                base.verify_face(source, output, coverage, weight)
                faces.append({'weight': weight, 'source': source_relative, 'sourceSha256': base.digest(source.read_bytes()), 'file': output.name, 'bytes': output.stat().st_size, 'sha256': base.digest(output.read_bytes()), 'codepoints': base.codepoints(coverage), 'systemFallbackCodepoints': base.codepoints(values - coverage)})
            manifest = {'format': 'noto-lab-subsets-v1', 'scope': scope, 'family': 'Noto Sans SC Lab ' + scope.title(), 'package': '@fontsource/noto-sans-sc', 'packageVersion': package['version'], 'license': {'spdx': 'OFL-1.1', 'file': 'OFL.txt', 'sha256': base.digest((OUTPUT / 'OFL.txt').read_bytes())}, 'tools': {'fonttools': base.FONTTOOLS_VERSION, 'brotli': base.BROTLI_VERSION}, 'sourceInputsSha256': inputs.encode_bindings(bindings), 'catalogSlugs': sorted(inputs.catalog({})), 'coverageRule': 'Both locale shells and rendered catalog metadata/planned cards for index; all unregistered content and dynamic demo text for fallback. Exact 400/700 masters only. Symbols outside the original CJK master use Geist/system fonts; no Fontsource chunk fallback.', 'faces': faces}
            manifest_path.write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8', newline='\n')
            css_path.write_text(css_for(scope, faces), encoding='utf-8', newline='\n')
        manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
        for file, digest in inputs.decode_bindings(manifest['sourceInputsSha256']).items():
            assert base.digest((ROOT / file).read_bytes()) == digest, 'Lab source changed; regenerate subsets'
        # The recorded catalog is an authoring snapshot. Node validates every
        # installed page and composes its missing index glyphs at ordinary build time.
        assert [face['weight'] for face in manifest['faces']] == [400, 700]
        for face in manifest['faces']:
            source, output = base.PACKAGE / face['source'], OUTPUT / face['file']
            assert base.digest(source.read_bytes()) == face['sourceSha256']
            assert base.digest(output.read_bytes()) == face['sha256']
            assert output.stat().st_size == face['bytes']
            with TTFont(source, recalcTimestamp=False) as original:
                expected = {int(code[2:], 16) for code in face['codepoints']}
                master_codes = set(original.getBestCmap())
                assert expected <= master_codes
            if scope == 'fallback':
                assert codes[face['weight']] & master_codes <= expected, 'Generic copy changed; regenerate subsets'
            base.verify_face(source, output, expected, face['weight'])
        # Whitespace is formatting-only; face declarations and coverage are exact.
        assert ''.join(css_path.read_text(encoding='utf-8').split()) == ''.join(css_for(scope, manifest['faces']).split())
        print(f"PASS lab-{scope}: two real weights, {sum(face['bytes'] for face in manifest['faces'])} bytes; exact recorded outlines/metrics; current composed coverage checked by Node", flush=True)


if __name__ == '__main__':
    main()
