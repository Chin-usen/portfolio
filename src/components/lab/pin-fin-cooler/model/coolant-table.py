"""Authoring-only generator for the pin-fin coolant property tables.

The browser never runs this script. It writes ../coolant-data.ts from CoolProp
(MIT licence), pinned below, so the committed table is reproducible:

    python -m venv .coolprop && .coolprop/bin/pip install CoolProp==8.0.0
    .coolprop/bin/python src/components/lab/pin-fin-cooler/model/coolant-table.py [--check]

Water: saturated liquid, IAPWS-95 equation of state with the IAPWS 2008
viscosity and IAPWS 2011 thermal-conductivity formulations.
50 % ethylene glycol: CoolProp incompressible fluid MEG at 50 % mass fraction,
fitted to Melinder, "Properties of Secondary Working Fluids for Indirect
Systems", IIR, 2010. Valid 0-100 C in CoolProp; the page flags extrapolation.
"""
from __future__ import annotations

import argparse
import subprocess
from pathlib import Path

import CoolProp
from CoolProp.CoolProp import PropsSI

ROOT = Path(__file__).resolve().parents[5]
OUTPUT = ROOT / "src/components/lab/pin-fin-cooler/coolant-data.ts"
VERSION = "8.0.0"


def rows(fluid: str, temperatures: range):
    for celsius in temperatures:
        kelvin = celsius + 273.15
        if fluid == "Water":
            state = ("T", kelvin, "Q", 0, "Water")
        else:
            state = ("T", kelvin, "P", 2e5, "INCOMP::MEG-50%")
        density = PropsSI("D", *state)
        cp = PropsSI("C", *state)
        conductivity = PropsSI("L", *state)
        viscosity = PropsSI("V", *state)
        yield [celsius, round(density, 2), round(cp, 1), round(conductivity, 5), float(f"{viscosity:.5g}")]


def render() -> str:
    water = list(rows("Water", range(5, 151, 5)))
    glycol = list(rows("MEG", range(0, 101, 5)))

    def table(data):
        return "[\n" + "".join(f"    [{', '.join(repr(value) for value in row)}],\n" for row in data) + "  ]"

    return (
        "// Generated by model/coolant-table.py with CoolProp "
        + VERSION
        + "; do not edit by hand.\n"
        "// Columns: temperature °C, density kg/m³, cp J/(kg·K), k W/(m·K), dynamic viscosity Pa·s.\n"
        "export type CoolantRow = readonly [number, number, number, number, number];\n\n"
        "export const COOLANT_SOURCES = {\n"
        "  water:\n"
        "    'Saturated liquid water, IAPWS-95 with IAPWS 2008 viscosity and IAPWS 2011 conductivity (CoolProp "
        + VERSION
        + ")',\n"
        "  glycol50:\n"
        "    'Ethylene glycol–water, 50 % by mass: Melinder (2010), IIR, via CoolProp "
        + VERSION
        + " incompressible fluid MEG',\n"
        "} as const;\n\n"
        "export const WATER_TABLE: readonly CoolantRow[] = "
        + table(water)
        + ";\n\n"
        "export const GLYCOL50_TABLE: readonly CoolantRow[] = "
        + table(glycol)
        + ";\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    assert CoolProp.__version__ == VERSION, f"CoolProp {VERSION} required"
    text = render()
    if args.check:
        scratch = OUTPUT.with_suffix(".check.ts")
        scratch.write_text(text, encoding="utf-8", newline="\n")
        try:
            subprocess.run(["node", str(ROOT / "node_modules/prettier/bin/prettier.cjs"), "--write", str(scratch)], check=True, cwd=ROOT)
            assert scratch.read_text(encoding="utf-8") == OUTPUT.read_text(encoding="utf-8"), "coolant-data.ts differs"
        finally:
            scratch.unlink(missing_ok=True)
        print("PASS: coolant-data.ts reproduces")
        return
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    subprocess.run(["node", str(ROOT / "node_modules/prettier/bin/prettier.cjs"), "--write", str(OUTPUT)], check=True, cwd=ROOT)
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
